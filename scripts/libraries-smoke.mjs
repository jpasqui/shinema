async function startServer() {
  server = spawn(
    join(
      root,
      'target/debug/shinema-server' +
        (process.platform === 'win32' ? '.exe' : ''),
    ),
    [],
    {
      cwd: root,
      env: environment,
      stdio: ['ignore', 'ignore', 'pipe'],
      windowsHide: true,
    },
  );
  server.stderr.on(
    'data',
    (bytes) => (serverLog = (serverLog + bytes.toString()).slice(-16384)),
  );
  let spawnError;
  server.once('error', (error) => (spawnError = error));
  const deadline = Date.now() + 90000;
  while (Date.now() < deadline) {
    if (spawnError) {
      server = undefined;
      throw spawnError;
    }
    if (server.exitCode !== null)
      throw new Error('Synthetic server exited: ' + serverLog);
    try {
      if (
        (await fetch(origin + '/health', { signal: AbortSignal.timeout(500) }))
          .ok
      )
        return;
    } catch {}
    await sleep(100);
  }
  throw new Error(
    'Synthetic loopback server did not become ready: ' + serverLog,
  );
}
async function stopServer() {
  if (!server || server.exitCode !== null) return;
  const stopped = once(server, 'exit');
  server.kill();
  await withinLibraryDeadline(stopped, 5000);
  server = undefined;
}
async function response(path, { admin = false, body, ...options } = {}) {
  return fetch(origin + path, {
    ...options,
    signal: AbortSignal.timeout(10000),
    headers: {
      ...(admin ? { Authorization: `Bearer ${token}` } : {}),
      ...(body === undefined ? {} : { 'Content-Type': 'application/json' }),
      ...options.headers,
    },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
  });
}
